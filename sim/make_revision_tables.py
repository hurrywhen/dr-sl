#!/usr/bin/env python3
"""Generate LaTeX result tables for the revised manuscript from archived JSON."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "results" / "revision_20261118"
TEX = ROOT / "latex" / "revision_results.tex"


def pct(x):
    return "--" if x is None else f"{100*x:.1f}\\%"


def num(x, d=3):
    return "--" if x is None else f"{x:.{d}f}"


def ci(obj):
    if not obj or not obj.get("ci95"):
        return "--"
    lo, hi = obj["ci95"]
    if lo is None or hi is None:
        return "--"
    return f"[{lo:.3f}, {hi:.3f}]"


def main():
    off = json.loads((OUT / "offline_summary.json").read_text())
    online_path = OUT / "online_audit_summary.json"
    online = json.loads(online_path.read_text()) if online_path.exists() else None
    line = []
    line.append("% Auto-generated by sim/make_revision_tables.py. Do not edit by hand.")
    line.append("\\begin{table}[!t]\\centering\\small")
    line.append("\\caption{Revised deterministic runtime-S track: closed-loop release and external gold-literal audit. Oracle-S uses gold annotations inside the policy and is an upper-bound reference, not a deployment result. Runtime-S uses extractor output only. Gold-literal hit rate is measured after the local decision is frozen.}")
    line.append("\\label{tab:runtime_oracle}")
    line.append("\\begin{tabular}{@{}llcccc@{}}\\toprule")
    line.append("Dataset & $S$ source & $n$ & local release & gold $L$ & recall \\\\ \\midrule")
    for dataset in ("test160", "mixed120", "holdout80"):
        for sset in ("oracle_gold", "runtime"):
            key = f"{dataset}/{sset}/closed_loop"
            if key not in off["methods"]:
                continue
            m = off["methods"][key]
            line.append(f"{dataset} & {sset.replace('_gold','')} & {m['n']} & {pct(m['release_rate'])} & {num(m['gold_L']['estimate'])} {ci(m['gold_L'])} & {num(m['recall']['estimate'])} {ci(m['recall'])} \\\\")
    line.append("\\bottomrule\\end{tabular}\\end{table}")

    line.append("\\begin{table}[!t]\\centering\\small")
    line.append("\\caption{Frozen holdout ($n=80$): fair runtime-S methods under the same local gate. External columns are controlled-disclosure audits on the pre-specified 40-instance subset, not local release inputs.}")
    line.append("\\label{tab:holdout_methods}")
    line.append("\\begin{tabular}{@{}lccccc@{}}\\toprule")
    line.append("Method & local release & $U_{local}$ & gold $L$ & external $L_{max}$ & judge $U_{sem}$ \\\\ \\midrule")
    for method in ("hardline_only", "generalization_only", "closed_loop", "intact_style", "prism_random"):
        key = f"holdout80/runtime/{method}"
        m = off["methods"][key]
        ext = "--"
        jud = "--"
        if online and method in online.get("by_method", {}):
            om = online["by_method"][method]
            if om.get("external_L_max"):
                ext = f"{num(om['external_L_max']['estimate'])} {ci(om['external_L_max'])}"
            if om.get("semantic_judge"):
                jud = f"{num(om['semantic_judge']['estimate'])} {ci(om['semantic_judge'])}"
        line.append(f"{method.replace('_', '\\_')} & {pct(m['release_rate'])} & {num(m['U_local']['estimate'])} & {num(m['gold_L']['estimate'])} & {ext} & {jud} \\\\")
    line.append("\\bottomrule\\end{tabular}\\end{table}")

    if online:
        z = online.get("zero_observation", {})
        line.append("\\begin{table}[!t]\\centering\\small")
        line.append("\\caption{External audit coverage on the frozen holdout subset. Zero observed hits, if present, are scoped to these attackers and grading protocol; no pooled binomial guarantee is claimed.}")
        line.append("\\label{tab:audit_coverage}")
        line.append("\\begin{tabular}{@{}lr@{}}\\toprule Quantity & Value \\\\ \\midrule")
        for k, label in (("n_instances", "instances"), ("n_attackers", "attackers"),
                         ("n_strategies", "strategies"), ("n_model_calls", "model calls"),
                         ("n_unique_questions", "unique questions"), ("observed_hits", "observed hits")):
            line.append(f"{label} & {z.get(k, '--')} \\\\")
        line.append("\\bottomrule\\end{tabular}\\end{table}")
        conf = online.get("threshold_confusion", {})
        if conf:
            line.append("\\begin{table}[!t]\\centering\\small")
            line.append("\\caption{Local release vs offline semantic-judge threshold ($U\\ge0.5$) on audited holdout artifacts. The judge is not a local release input.}")
            line.append("\\label{tab:threshold_confusion}")
            line.append("\\begin{tabular}{@{}lr@{}}\\toprule Agreement cell & count \\\\ \\midrule")
            for k in sorted(conf):
                line.append(f"{k.replace('_',' ')} & {conf[k]} \\\\")
            line.append("\\bottomrule\\end{tabular}\\end{table}")

    TEX.write_text("\n".join(line) + "\n", encoding="utf-8")
    print(f"wrote {TEX}")


if __name__ == "__main__":
    main()
