#!/usr/bin/env python3
"""Generate LaTeX result tables for the Route-A revision from archived JSON.

Tables are deliberately narrow (<=5 short columns, footnotesize) so they fit a
single IEEE column without overfull boxes.  Two files are produced:
  revision_results.tex      -- full set (main + journal)
  revision_results_conf.tex -- condensed subset (conference)
Do not edit the generated .tex by hand.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "results" / "revision_20261121"
TEX = ROOT / "latex" / "revision_results.tex"
TEXCONF = ROOT / "latex" / "revision_results_conf.tex"


def pct(x):
    return "--" if x is None else f"{100*x:.1f}\\%"


def num(x, d=3):
    return "--" if x is None else f"{x:.{d}f}"


def ci(obj, d=3):
    if not obj or not obj.get("ci95"):
        return ""
    lo, hi = obj["ci95"]
    if lo is None or hi is None:
        return ""
    return f" [{lo:.{d}f},{hi:.{d}f}]"


def load(name):
    p = OUT / name
    return json.loads(p.read_text()) if p.exists() else None


def tbl(label, caption, header, rows, size="\\footnotesize"):
    L = [f"\\begin{{table}}[!t]\\centering{size}",
         f"\\caption{{{caption}}}", f"\\label{{{label}}}",
         "\\begin{tabular}{@{}" + "l" + "c" * (len(header) - 1) + "@{}}\\toprule",
         " & ".join(header) + " \\\\ \\midrule"]
    L += [" & ".join(r) + " \\\\" for r in rows]
    L += ["\\bottomrule\\end{tabular}\\end{table}"]
    return "\n".join(L)


def main():
    off = load("offline_summary.json")
    strat = load("stratified_summary.json")
    online = load("online_audit_summary.json")
    down = load("downstream_summary.json")
    full, conf = [], []
    full.append("% Auto-generated by sim/make_revision_tables.py. Do not edit by hand.")
    conf.append("% Auto-generated (condensed). Do not edit by hand.")

    # 1. Release-stratified risk (holdout-1, closed_loop).
    if strat:
        cl = strat["offline"]["holdout80"]["closed_loop"]
        rows = []
        for s in ("ALL", "PASS", "INFEASIBLE"):
            d = cl[s]
            rows.append([s, str(d["n"]), pct(d.get("gold_residue_fraction")),
                         num(d.get("mean_gold_L")), num(d.get("mean_recall"))])
        t = tbl("tab:stratified",
                "Holdout-1 closed loop, stratified by local decision. The primary safety "
                "metric is the conditional residue rate given local PASS (FalseRelease). "
                "Whole-set averages mask the released subgroup.",
                ["Stratum", "$n$", "residue \\%", "gold $L$", "recall"], rows)
        full.append(t); conf.append(t)

        # 2. Per-domain.
        rows = []
        for dom, d in cl["by_domain"].items():
            rows.append([dom, pct(d["release_rate"]), str(d["PASS"]["n"]),
                         pct(d["FalseRelease_gold"]), num(d["PASS"].get("mean_gold_L"))])
        t = tbl("tab:domain",
                "Holdout-1 closed loop by domain. Banking releases 20/20 and every released "
                "instance retains gold literals; legal PASS is 10/10 with residue.",
                ["Domain", "release \\%", "PASS $n$", "FalseRelease \\%", "PASS gold $L$"], rows)
        full.append(t); conf.append(t)

        # 3. Vocabulary shift (holdout-1 vs holdout-2).
        h2 = strat["offline"]["holdout80_v2"]["closed_loop"]
        r1 = off["methods"]["holdout80/runtime/closed_loop"]["release_rate"]
        r2 = off["methods"]["holdout80_v2/runtime/closed_loop"]["release_rate"]
        rows = [
            ["extractor recall", num(cl["ALL"]["mean_recall"]), num(h2["ALL"]["mean_recall"])],
            ["local release \\%", pct(r1), pct(r2)],
            ["gold $L$ (ALL)", num(cl["ALL"]["mean_gold_L"]), num(h2["ALL"]["mean_gold_L"])],
            ["FalseRelease (gold)", pct(cl["FalseRelease_gold"]), pct(h2["FalseRelease_gold"])],
        ]
        t = tbl("tab:vocabshift",
                "Vocabulary shift: holdout-1 shares the extractor lexicons; holdout-2 uses a "
                "disjoint vocabulary. Recall collapses and nearly every released instance leaks.",
                ["Quantity", "holdout-1", "holdout-2"], rows)
        full.append(t); conf.append(t)

        # 4. Residual-report recall.
        rr = strat["offline"]["holdout80"]["residual_report_recall_closed_loop"]
        rows = []
        for s in ("PASS", "INFEASIBLE"):
            d = rr[s]
            rows.append([s, str(d.get("n_instances_with_residue", 0)),
                         num(d.get("mean_report_recall_of_gold_residue"))])
        t = tbl("tab:residual",
                "Residual-report coverage of true gold residue (holdout-1 closed loop). "
                "Extractor-missed attributes cannot appear in runtime-S reports; coverage is 0.",
                ["Stratum", "$n$ w/ residue", "report recall"], rows)
        full.append(t)

    # 5. Paired closed_loop - generalization_only.
    if off:
        rows = []
        for metric, key in (("release", "release_delta"), ("gold $L$", "gold_L_delta"),
                            ("$U_{local}$", "U_delta")):
            cells = [metric]
            for ds in ("holdout80", "holdout80_v2"):
                p = off["paired"].get(f"{ds}/runtime/closed_loop_minus_generalization", {}).get(key)
                cells.append(num(p["estimate"]) + ci(p, 2) if p else "--")
            rows.append(cells)
        t = tbl("tab:paired",
                "Paired closed-loop minus generalization-only (instance-cluster 95\\% CI). "
                "Release and gold-leakage deltas are zero; local utility is lower for the loop.",
                ["Metric $\\Delta$", "holdout-1", "holdout-2"], rows)
        full.append(t); conf.append(t)

        # 6. Fair methods, local columns.
        rows = []
        for m in ("hardline_only", "generalization_only", "closed_loop", "intact_style", "prism_random"):
            d = off["methods"][f"holdout80/runtime/{m}"]
            rows.append([m.replace("_", "\\_"), pct(d["release_rate"]),
                         num(d["U_local"]["estimate"]), num(d["gold_L"]["estimate"])])
        t = tbl("tab:methods",
                "Holdout-1 fair runtime-S methods under the same local gate (local columns). "
                "The loop matches generalization-only on release and leakage but lowers utility.",
                ["Method", "release \\%", "$U_{local}$", "gold $L$"], rows)
        full.append(t)

    # 7. External / judge / downstream columns (holdout-1 only).
    if strat and "online_stratified" in strat:
        rows = []
        for m in ("hardline_only", "generalization_only", "closed_loop", "intact_style",
                  "prism_random", "direct_forward"):
            om = strat["online_stratified"].get(m, {}).get("ALL")
            if not om or om.get("n", 0) == 0:
                continue
            ext = num(om.get("mean_external_L_max"))
            jud = num(om.get("mean_judge_U"))
            du = "--"
            if down and m in down.get("by_method", {}):
                du = num(down["by_method"][m]["ALL"]["estimate"])
            rows.append([m.replace("_", "\\_"), ext, jud, du])
        t = tbl("tab:external",
                "Holdout-1 controlled-disclosure audit (40-instance subset): external max hit "
                "rate, offline artifact-judge utility, and downstream-task utility. "
                "direct\\_forward is the unprocessed-X attacker reference.",
                ["Method", "ext $L_{max}$", "judge $U$", "task $U$"], rows)
        full.append(t)

        # 8. Corrected audit coverage.
        if "audit_coverage" in strat:
            z = strat["audit_coverage"]
            rows = [[lab, str(z[k])] for k, lab in (
                ("n_instances", "instances"), ("n_attackers", "attackers"),
                ("n_strategies", "strategies"), ("n_attack_calls", "attack calls"),
                ("n_judge_calls", "judge calls"), ("n_question_evaluations", "question evaluations"),
                ("n_unique_instance_question_pairs", "unique instance--question pairs"),
                ("n_unique_question_texts", "unique question texts"),
                ("total_hit_evaluations", "total hit evaluations"))]
            t = tbl("tab:coverage",
                    "Corrected audit coverage. Question evaluations count repeated assessments; "
                    "hits are total hit evaluations, not distinct leaked values.",
                    ["Quantity", "Value"], rows)
            full.append(t); conf.append(t)

    # 9. Calibration (overall) with CIs.
    if strat and "calibration" in strat:
        o = strat["calibration"]["overall"]
        rows = []
        for k, lab in (("rho", "Spearman $\\rho$"), ("mae", "MAE"),
                       ("threshold_agreement", "threshold agree.")):
            d = o[k]
            rows.append([lab, num(d["estimate"]) + ci(d)])
        t = tbl("tab:calibration",
                "Local utility surrogate vs offline judge (holdout-1 audited artifacts), "
                "instance-cluster 95\\% CI. Correlation is weak; the surrogate is not calibrated.",
                ["Metric", "estimate [95\\% CI]"], rows)
        full.append(t)

        # 10. Per-method threshold confusion (closed_loop).
        bm = strat["calibration"]["by_method"].get("closed_loop", {})
        conf_m = bm.get("threshold_confusion", {})
        if conf_m:
            rows = [["closed\\_loop",
                     str(conf_m.get("local_1_judge_1", 0)), str(conf_m.get("local_1_judge_0", 0)),
                     str(conf_m.get("local_0_judge_1", 0)), str(conf_m.get("local_0_judge_0", 0))]]
            t = tbl("tab:confusion",
                    "Closed-loop local release vs offline-judge threshold ($U\\ge0.5$). "
                    "FP = released locally but judged below threshold offline.",
                    ["Method", "TP", "FP", "FN", "TN"], rows)
            full.append(t)

    # 11. Downstream task utility stratified.
    if down:
        rows = []
        for m in ("closed_loop", "generalization_only"):
            d = down["by_method"][m]
            rows.append([m.replace("_", "\\_"), num(d["ALL"]["estimate"]),
                         num(d["PASS"]["estimate"]), num(d["INFEASIBLE"]["estimate"])])
        t = tbl("tab:downstream",
                "Downstream-task utility (answer-from-material judged vs X-reference), "
                "stratified by local decision. PASS retains more task utility than INFEASIBLE.",
                ["Method", "ALL", "PASS", "INFEASIBLE"], rows)
        full.append(t)

    TEX.write_text("\n\n".join(full) + "\n", encoding="utf-8")
    TEXCONF.write_text("\n\n".join(conf) + "\n", encoding="utf-8")
    print(f"wrote {TEX} ({len(full)} blocks) and {TEXCONF} ({len(conf)} blocks)")


if __name__ == "__main__":
    main()
