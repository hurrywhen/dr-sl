#!/usr/bin/env python3
"""Generate merged LaTeX result tables for the round-3 Route-A manuscript.

Reads archived JSON from results/revision_20261121 (round 2) and
results/revision_round3 (round 3).  Tables are narrow (<=6 short columns,
footnotesize) to fit a single IEEE column.  Two files are produced:
  revision_results.tex      -- full set (main + journal)
  revision_results_conf.tex -- condensed subset (conference)
Do not edit the generated .tex by hand.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
R2 = ROOT / "results" / "revision_20261121"
R3 = ROOT / "results" / "revision_round3"
TEX = ROOT / "latex" / "revision_results.tex"
TEXCONF = ROOT / "latex" / "revision_results_conf.tex"

ABBR = {"hardline_only": "HL", "generalization_only": "GEN", "closed_loop": "CL",
        "intact_style": "INT", "prism_random": "PRISM", "direct_forward": "DF"}


def load(base, name):
    p = base / name
    return json.loads(p.read_text()) if p.exists() else None


def pct(x):
    return "--" if x is None else f"{100*x:.1f}"


def num(x, d=3):
    return "--" if x is None else f"{x:.{d}f}"


def wil(w):
    if not w:
        return "--"
    lo, hi = w
    f = lambda v: f"{v:.3f}".replace("0.", ".")
    return f"[{f(lo)},{f(hi)}]"


def ci(obj, d=3):
    if not obj or not obj.get("ci95"):
        return "--"
    lo, hi = obj["ci95"]
    if lo is None or hi is None:
        return "--"
    return f"[{lo:.{d}f},{hi:.{d}f}]"


def tbl(label, caption, header, rows, size="\\footnotesize", colspec=None, tabcolsep=None):
    cs = colspec or ("@{}l" + "c" * (len(header) - 1) + "@{}")
    sep = f"\\setlength{{\\tabcolsep}}{{{tabcolsep}pt}}" if tabcolsep else ""
    L = [f"\\begin{{table}}[!t]\\centering{sep}{size}",
         f"\\caption{{{caption}}}", f"\\label{{{label}}}",
         "\\begin{tabular}{" + cs + "}\\toprule",
         " & ".join(header) + " \\\\ \\midrule"]
    L += [" & ".join(r) + " \\\\" for r in rows]
    L += ["\\bottomrule\\end{tabular}\\end{table}"]
    return "\n".join(L)


def main():
    off2 = load(R2, "offline_summary.json")
    strat = load(R3, "stratified_summary.json")
    h3 = load(R3, "offline_h3_summary.json")
    down = load(R3, "downstream_summary.json")
    probe = load(R3, "residual_probe.json")
    openatk = load(R3, "online_open_summary.json")
    full, conf = [], []
    full.append("% Auto-generated by sim/make_revision_tables.py (round 3). Do not edit by hand.")
    conf.append("% Auto-generated (condensed, round 3). Do not edit by hand.")

    cl1 = strat["offline"]["holdout80"]["closed_loop"]
    cl2 = strat["offline"]["holdout80_v2"]["closed_loop"]

    # 1. Release-stratified risk with Wilson CIs (holdout-1, closed loop).
    rows = []
    for s in ("ALL", "PASS", "INFEASIBLE"):
        d = cl1[s]
        rows.append([s, str(d["n"]), pct(d.get("gold_residue_fraction")),
                     wil(d.get("gold_residue_fraction_wilson95")),
                     num(d.get("mean_gold_L"))])
    t = tbl("tab:stratified",
            "Holdout-1 closed loop stratified by local decision (Wilson 95\\% intervals). "
            "The primary safety metric is the conditional residue rate given local PASS "
            "(FR$_{gold}$); whole-set averages mask the released subgroup.",
            ["Stratum", "$n$", "residue \\%", "95\\% CI", "gold $L$"], rows)
    full.append(t); conf.append(t)

    # 2. Per-domain with Wilson CIs.
    rows = []
    for dom, d in cl1["by_domain"].items():
        rows.append([dom, pct(d["release_rate"]), str(d["PASS"]["n"]),
                     pct(d["FalseRelease_gold"]), wil(d.get("FalseRelease_gold_wilson95")),
                     num(d["PASS"].get("mean_gold_L"))])
    t = tbl("tab:domain",
            "Holdout-1 closed loop by domain. Banking releases 20/20 with residue in every "
            "released instance; legal PASS is 10/10 with residue. All 20 banking instances "
            "enter the harmful utility fallback (mechanism analysis in text).",
            ["Domain", "rel.\\ \\%", "PASS $n$", "FR$_{gold}$ \\%", "95\\% CI", "PASS gold $L$"], rows)
    full.append(t); conf.append(t)

    # 3. Merged method comparison: local + external + task utility + paired deltas.
    onl = strat["online_stratified"]
    rows = []
    for m in ("hardline_only", "generalization_only", "closed_loop", "intact_style",
              "prism_random", "direct_forward"):
        o = onl.get(m, {}).get("ALL", {})
        du = down["by_method"].get(m, {}).get("ALL", {}).get("estimate") if down else None
        if m == "direct_forward":
            rows.append([ABBR[m], "--", "--", "--",
                         num(o.get("mean_external_L_max")), num(o.get("mean_judge_U")), "--"])
            continue
        d = off2["methods"][f"holdout80/runtime/{m}"]
        rows.append([ABBR[m], pct(d["release_rate"]), num(d["U_local"]["estimate"]),
                     num(d["gold_L"]["estimate"]), num(o.get("mean_external_L_max")),
                     num(o.get("mean_judge_U")), num(du)])
    rows.append(["\\multicolumn{7}{@{}l@{}}{\\emph{Paired $\\Delta$ CL$-$GEN; release/gold-$L$ deltas 0; CIs in text}}"])
    for ds, key in (("h1", "holdout80"), ("h2", "holdout80_v2")):
        p = off2["paired"][f"{key}/runtime/closed_loop_minus_generalization"]
        row = [f"$\\Delta$ {ds}", num(p["release_delta"]["estimate"], 1),
               num(p["U_delta"]["estimate"]),
               num(p["gold_L_delta"]["estimate"], 1), "--", "--", "--"]
        if ds == "h1":
            ext_d = (onl["closed_loop"]["ALL"]["mean_external_L_max"]
                     - onl["generalization_only"]["ALL"]["mean_external_L_max"])
            jud_d = (onl["closed_loop"]["ALL"]["mean_judge_U"]
                     - onl["generalization_only"]["ALL"]["mean_judge_U"])
            row[4] = num(ext_d, 1)
            row[5] = num(jud_d)
            if down:
                pd = down["paired_closed_minus_generalization"]
                row[6] = num(pd["estimate"])
        rows.append(row)
    if h3:
        p = h3["paired"]["holdout80_v3/original"]
        rows.append(["$\\Delta$ h3", num(p["release_delta"]["estimate"], 1),
                     num(p["U_delta"]["estimate"]),
                     num(p["gold_L_delta"]["estimate"], 1), "--", "--", "--"])
    t = tbl("tab:methods",
            "Holdout-1 method comparison under the same local gate (40-instance audited "
            "subset for external columns). HL=hardline-only, GEN=generalization-only, "
            "CL=closed loop, INT=INTACT-style proxy, PRISM=random replacement, "
            "DF=direct-forward reference. ext=external max hit rate; judge=offline "
            "artifact-judge utility; task=reference-answer preservation. Paired rows: "
            "CL$-$GEN; the task-$U$ delta uses the round-3 rerun. Local-utility delta "
            "sign varies by dataset; release/leakage deltas are zero throughout.",
            ["Method", "rel.\\ \\%", "$U_{loc}$", "gold $L$", "ext $L$", "judge $U$", "task $U$"],
            rows, tabcolsep=2)
    full.append(t); conf.append(t)

    # 4. Vocabulary shift + dose-response (merged).
    rows = [
        ["holdout-1", "1.000", num(cl1["ALL"]["mean_recall"]),
         pct(off2["methods"]["holdout80/runtime/closed_loop"]["release_rate"]),
         pct(cl1["FalseRelease_gold"]), wil(cl1["PASS"].get("gold_residue_fraction_wilson95"))],
        ["holdout-2", "0.000", num(cl2["ALL"]["mean_recall"]),
         pct(off2["methods"]["holdout80_v2/runtime/closed_loop"]["release_rate"]),
         pct(cl2["FalseRelease_gold"]), wil(cl2["PASS"].get("gold_residue_fraction_wilson95"))],
    ]
    if h3:
        for tag, v in h3["dose_response"].items():
            rows.append([f"drift {tag}", num(v["realized_old_vocab_fraction"]),
                         num(v["recall"]), pct(v["release_rate"]),
                         pct(v["FalseRelease_gold"]), wil(v["FalseRelease_gold_wilson95"])])
    t = tbl("tab:vocab",
            "Vocabulary-shift stress and dose--response (closed loop, original extractor). "
            "overlap = realized fraction of lexicon-dependent gold values from the old "
            "vocabulary. holdout-2 is a constructive fully-disjoint lexicon ablation, not a "
            "deployment failure rate; the drift series holds templates constant and varies "
            "only overlap (40 instances/level).",
            ["Condition", "overlap", "recall", "rel.\\ \\%", "FR$_{gold}$ \\%", "95\\% CI"], rows)
    full.append(t); conf.append(t)

    # 5. Fixed-extractor contrast (holdout-3 confirmatory + h1/h2 diagnostic).
    if h3:
        rows = []
        for ex, m, lab in (("original", "closed_loop", "h3 original"),
                           ("fixed", "closed_loop", "h3 fixed"),
                           ("original", "closed_loop_covgate", "h3 orig.+CG"),
                           ("fixed", "closed_loop_covgate", "h3 fixed+CG")):
            v = h3["methods"][f"holdout80_v3/{ex}/{m}"]
            rows.append([lab, num(v["recall"]["estimate"]),
                         num(v["task_recall"]["estimate"]) if v["task_recall"] else "--",
                         pct(v["release_rate"]), pct(v["FalseRelease_gold"]),
                         pct(v["utility_fallback_fraction"])])
        rows.append(["\\multicolumn{6}{@{}l@{}}{\\emph{Diagnostic (defects discovered on these sets; not confirmatory)}}"])
        for ds, lab in (("holdout80_diag_fixed", "h1 fixed"), ("holdout80_v2_diag_fixed", "h2 fixed")):
            v = h3["methods"][f"{ds}/fixed/closed_loop"]
            rows.append([lab, num(v["recall"]["estimate"]),
                         num(v["task_recall"]["estimate"]) if v["task_recall"] else "--",
                         pct(v["release_rate"]), pct(v["FalseRelease_gold"]),
                         pct(v["utility_fallback_fraction"])])
        t = tbl("tab:fixcontrast",
                "Fixed-extractor contrast (Wilson intervals in text). The fixed variant "
                "repairs clear defects only (money pattern wiring, ASCII email local part, "
                "allergy label/collision); no lexicon additions. Holdout-3 (natural 50/50 "
                "vocabulary mix, new templates) is confirmatory. CG = coverage gate "
                "(UNSCORABLE$\\to$human when no task attribute extracted). Fixing defects "
                "removes gold false release on shared-vocabulary h1 but not under "
                "vocabulary shift.",
                ["Config", "recall", "task rec.", "rel.\\ \\%", "FR$_{gold}$ \\%", "fallb.\\ \\%"],
                rows, tabcolsep=3)
        full.append(t); conf.append(t)

    # 6. Fallback mechanism.
    rows = []
    for ds, lab in (("holdout80", "h1"), ("holdout80_v2", "h2")):
        m = strat["mechanism"][ds]["closed_loop"]
        rows.append([lab, num(m["mean_attribute_recall"]), num(m["mean_task_relevant_recall"]),
                     pct(m["harmful_fallback_fraction"]),
                     f"{m['released_via_harmful_fallback']}/{m['n_released']}",
                     num(m["FalseRelease_gold_harmful_fallback_released"])])
    if h3:
        h3rows = [json.loads(l) for l in (R3 / "offline_h3.jsonl").open(encoding="utf-8")]
        rs = [r for r in h3rows if r["dataset"] == "holdout80_v3"
              and r["extractor"] == "original" and r["method"] == "closed_loop"]
        rel = [r for r in rs if r["release"]]
        hf = [r for r in rs if r["utility_fallback"] and r["n_gold_task"] > 0]
        hf_rel = [r for r in hf if r["release"]]
        tr = [r["task_recall"] for r in rs if r["task_recall"] is not None]
        rows.append(["h3", num(sum(r["recall"] for r in rs) / len(rs)),
                     num(sum(tr) / len(tr)), pct(len(hf) / len(rs)),
                     f"{len(hf_rel)}/{len(rel)}",
                     num(sum(1 for r in hf_rel if r["gold_literal_hits"] > 0) / len(hf_rel)) if hf_rel else "--"])
    m1 = strat["mechanism"]["holdout80"]["closed_loop"]
    t = tbl("tab:mechanism",
            "Utility-gate fallback mechanism (closed loop, original extractor). Harmful "
            "fallback: gold task-relevant attributes exist but none were extracted, so "
            "local utility scores non-sensitive context retention instead. FR$_{gold}$ "
            "among released harmful-fallback instances vs "
            f"{num(m1['FalseRelease_gold_other_released'])} among other released "
            "instances on h1: worse extraction makes release easier.",
            ["Data", "attr rec.", "task rec.", "harmful FB \\%", "rel.\\ via FB", "FR$_{gold}$|FB"], rows)
    full.append(t)

    # 7. Merged utility measurement: calibration + confusion + downstream.
    rows = []
    cal = strat["calibration"]["overall"]
    for k, lab in (("rho", "Spearman $\\rho$ (tied ranks)"), ("mae", "MAE"),
                   ("threshold_agreement", "threshold agreement")):
        d = cal[k]
        rows.append([lab, num(d["estimate"]), ci(d)])
    bm = strat["calibration"]["by_method"]["closed_loop"]["threshold_confusion"]
    rows.append(["CL confusion TP/FP/FN/TN",
                 f"{bm.get('local_1_judge_1',0)}/{bm.get('local_1_judge_0',0)}/"
                 f"{bm.get('local_0_judge_1',0)}/{bm.get('local_0_judge_0',0)}", "--"])
    if down:
        for m, lab in (("closed_loop", "task $U$: CL"), ("generalization_only", "task $U$: GEN")):
            d = down["by_method"][m]
            rows.append([lab + " (ALL)", num(d["ALL"]["estimate"]), ci(d["ALL"])])
            rows.append([lab + " (PASS / INFEAS)",
                         f"{num(d['PASS']['estimate'])} / {num(d['INFEASIBLE']['estimate'])}", "--"])
        pd = down["paired_closed_minus_generalization"]
        rows.append(["task $U$ paired $\\Delta$ CL$-$GEN", num(pd["estimate"]), ci(pd)])
        rows.append(["judge exact agreement / MAE",
                     f"{num(down['judge_agreement']['exact_agreement'])} / "
                     f"{num(down['judge_agreement']['mae'])}", "--"])
    t = tbl("tab:utility",
            "Utility measurement (round-3 corrected). Calibration: local surrogate vs "
            "offline artifact judge, instance-cluster 95\\% CIs, average tied ranks. "
            "Task $U$ = reference-answer preservation (agreement with the answer from full "
            "$X$; not absolute correctness), explicit tasks, hash-cached answers, two "
            "judges. The surrogate is uncalibrated in absolute error and threshold "
            "decisions; rank correlation is moderate with wide intervals.",
            ["Quantity", "estimate", "95\\% CI"], rows)
    full.append(t)

    # 8. Residual-report two-type probe.
    if probe:
        rows = []
        for mode in ("exact", "evasion"):
            p = probe[mode]
            rows.append([mode, num(p["type_a_detected_first_eval"]),
                         num(p["type_a_report_coverage_among_infeasible"]),
                         num(p["type_a_removed_by_scrub"]),
                         num(p["type_b_report_coverage"])])
        t = tbl("tab:residual",
                "Constructed two-type residue probe (55 holdout-1 instances with gold "
                "residue). Type a: an extracted value re-inserted (exact = verbatim; "
                "evasion = normalized-equivalent variant that exact replacement misses). "
                "Type b: never-extracted gold residue. Report coverage is measured among "
                "INFEASIBLE loop exits; PASS instances have no report by construction. "
                "Detectable residue is reported/routed; never-extracted residue is invisible.",
                ["Mode", "type a detect", "type a report", "type a scrubbed", "type b report"], rows)
        full.append(t)

    # 9. Open-ended attack (exploratory FR_open-ended).
    if openatk and "open_attack_stratified" in strat:
        rows = []
        for m in ("closed_loop", "generalization_only", "direct_forward"):
            b = strat["open_attack_stratified"][m]
            a, p = b["ALL"], b.get("PASS", {})
            rows.append([ABBR[m], pct(a["FR_open_ended"]), wil(a["FR_open_ended_wilson95"]),
                         pct(p.get("FR_open_ended")) if p.get("n") else "--",
                         num(a["mean_L"])])
        t = tbl("tab:openattack",
                "Open-ended inference attack (no gold question types; exploratory "
                "FR$_{open}$, still literal-graded). DF is a reference under this protocol, "
                "not a theoretical attacker ceiling. Released artifacts remain highly "
                "recoverable even without question-type hints.",
                ["Method", "FR$_{open}$ \\%", "95\\% CI", "FR$_{open}$|PASS \\%", "mean $L$"], rows)
        full.append(t)

    TEX.write_text("\n\n".join(full) + "\n", encoding="utf-8")
    TEXCONF.write_text("\n\n".join(conf) + "\n", encoding="utf-8")
    print(f"wrote {TEX} ({len(full)-1} tables) and {TEXCONF} ({len(conf)-1} tables)")


if __name__ == "__main__":
    main()
